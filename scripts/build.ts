/**
 * Build both halves of the dsh-litnotes bundle.
 *
 *   node scripts/build.ts            # build host entry + client bundle
 *   node scripts/build.ts --check    # build and assert the artifacts are sane
 *   node scripts/build.ts --watch    # rebuild on source changes
 *
 * Outputs (committed release artifacts, listed in package.json `files`):
 *   index.js        Host half, one ESM file bundling src/host/**, no npm deps
 *   lib/client.js   Client half in the Harness module-loader factory format
 *
 * The repo is a plain package directory (no runtime node_modules): every
 * third-party runtime dependency is bundled at build time. `react` stays
 * external for the client because the Harness module table provides it.
 */

import { build, transformSync, type Plugin } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, statSync, watch, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ARGS = new Set(process.argv.slice(2))
const CHECK = ARGS.has('--check')
const WATCH = ARGS.has('--watch')
const ANALYZE = ARGS.has('--analyze')

/** Build budgets: fail the build when an artifact grows past these sizes. */
// Interim budgets while the client workstreams land; the release gate tightens
// these (DESIGN-V2 §10: client ≤ 620 KiB minified, goal ≤ 450 KiB).
const BUDGETS = { clientJs: 620 * 1024, clientCss: 160 * 1024, hostJs: 2 * 1024 * 1024 }

const PACKAGE = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')) as {
  name: string
  version: string
}
const BUNDLE_ID = PACKAGE.name
const BANNER = `/* ${BUNDLE_ID} — generated by scripts/build.ts; edit src/** instead. */`

/** CSS bytes embedded in the current client bundle (filled by the asset plugin). */
let embeddedCssBytes = 0

/**
 * The Harness platform module table provides these exact requests: `react`,
 * `react/jsx-runtime`, `react-dom`, `react-dom/client`. Keep them external and
 * bundle everything else (jsx-runtime is bundled by esbuild unless imported).
 */
const PLATFORM_EXTERNALS = new Set(['react', 'react-dom', 'react-dom/client'])

/** Externalize the platform-provided React runtime requests. */
function reactExternalPlugin(): Plugin {
  return {
    name: 'litnotes-react-external',
    setup(api) {
      api.onResolve({ filter: /^react(|-dom)(\/.*)?$/ }, (args) => {
        if (PLATFORM_EXTERNALS.has(args.path)) return { path: args.path, external: true }
        return undefined
      })
    },
  }
}

/** esbuild plugin: CSS → minified string, SVG → raw markup string. */
function assetPlugin(): Plugin {
  return {
    name: 'litnotes-assets',
    setup(api) {
      api.onLoad({ filter: /\.css$/ }, (args) => {
        const source = readFileSync(args.path, 'utf8')
        const minified = transformSync(source, {
          loader: 'css',
          minify: true,
          target: 'chrome110',
        }).code
        embeddedCssBytes += Buffer.byteLength(minified)
        return { contents: `export default ${JSON.stringify(minified)}`, loader: 'js' }
      })
      api.onLoad({ filter: /\.svg$/ }, (args) => ({
        contents: `export default ${JSON.stringify(readFileSync(args.path, 'utf8').trim())}`,
        loader: 'js',
      }))
    },
  }
}

/** Bundle the Host half to `index.js`; returns its byte size. */
async function buildHost(): Promise<number> {
  await build({
    absWorkingDir: ROOT,
    entryPoints: ['src/host/index.ts'],
    outfile: 'index.js',
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: ['node20.16'],
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    logLevel: 'silent',
    banner: { js: BANNER },
    define: { __LITNOTES_VERSION__: JSON.stringify(PACKAGE.version) },
  })
  const bytes = statSync(join(ROOT, 'index.js')).size
  if (bytes > BUDGETS.hostJs) {
    throw new Error(
      `host bundle ${(bytes / 1024).toFixed(1)} KiB exceeds budget ${(BUDGETS.hostJs / 1024).toFixed(0)} KiB`,
    )
  }
  return bytes
}

/** Bundle the Client half body and wrap it in the Harness module-loader format. */
async function buildClient(): Promise<{ js: number; css: number }> {
  mkdirSync(join(ROOT, '.build'), { recursive: true })
  const bodyPath = join(ROOT, '.build', 'client-body.js')
  embeddedCssBytes = 0
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['src/client/index.tsx'],
    outfile: bodyPath,
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: ['chrome110', 'firefox115', 'safari16'],

    minify: true,
    sourcemap: false,
    legalComments: 'none',
    logLevel: 'silent',
    define: { 'process.env.NODE_ENV': '"production"' },
    plugins: [reactExternalPlugin(), assetPlugin()],
    metafile: ANALYZE,
  })
  if (ANALYZE && result.metafile !== undefined) {
    writeFileSync(join(ROOT, '.build', 'client-metafile.json'), JSON.stringify(result.metafile))
  }

  const body = readFileSync(bodyPath, 'utf8')
  if (body.includes('__LITNOTES_')) throw new Error('an unreplaced build placeholder survived')

  const wrapped = `${BANNER}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(BUNDLE_ID)},
  factory(require) {
    'use strict';
    const module = { exports: {} };
    const exports = module.exports;
${body}
    const exported = module.exports;
    const main = exported.clientMain ?? (exported.default && exported.default.clientMain);
    return typeof main === 'function' ? main(require) : exported;
  },
});
`
  mkdirSync(join(ROOT, 'lib'), { recursive: true })
  const outFile = join(ROOT, 'lib', 'client.js')
  writeFileSync(outFile, wrapped)
  const bytes = Buffer.byteLength(wrapped)
  if (bytes > BUDGETS.clientJs) {
    throw new Error(
      `client bundle ${(bytes / 1024).toFixed(1)} KiB exceeds budget ${(BUDGETS.clientJs / 1024).toFixed(0)} KiB`,
    )
  }
  if (embeddedCssBytes > BUDGETS.clientCss) {
    throw new Error(
      `client CSS ${(embeddedCssBytes / 1024).toFixed(1)} KiB exceeds budget ${(BUDGETS.clientCss / 1024).toFixed(0)} KiB`,
    )
  }
  return { js: bytes, css: embeddedCssBytes }
}

/** Parse the generated artifacts as JavaScript (syntax gate). */
function checkSyntax(): void {
  mkdirSync(join(ROOT, '.build'), { recursive: true })
  const temp = join(ROOT, '.build', 'client-check.cjs')
  writeFileSync(temp, readFileSync(join(ROOT, 'lib', 'client.js'), 'utf8'))
  execFileSync(process.execPath, ['--check', temp], { stdio: 'pipe' })
  execFileSync(process.execPath, ['--check', join(ROOT, 'index.js')], { stdio: 'pipe' })
}

/** Report the two artifact sizes. */
function report(host: number, client: { js: number; css: number }): void {
  const kb = (bytes: number): string => `${(bytes / 1024).toFixed(1)} KiB`
  console.log(`[build] index.js ${kb(host)} · lib/client.js ${kb(client.js)} (css ${kb(client.css)})`)
}

/** One full build. */
async function run(): Promise<void> {
  const started = Date.now()
  const host = await buildHost()
  const client = await buildClient()
  if (CHECK) checkSyntax()
  report(host, client)
  if (CHECK) console.log(`[build] check passed in ${Date.now() - started} ms`)
}

if (WATCH) {
  console.log('[build] watching src/** (ctrl-c to stop)')
  void run().catch((error) => console.error('[build] failed:', error))
  let timer: NodeJS.Timeout | undefined
  watch(join(ROOT, 'src'), { recursive: true }, () => {
    if (timer) clearTimeout(timer)
    timer = setTimeout(() => {
      void run().catch((error) => console.error('[build] failed:', error))
    }, 120)
  })
} else {
  await run().catch((error) => {
    console.error('[build] FAILED:', error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
