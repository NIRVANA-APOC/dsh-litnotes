/**
 * Build the browser bundle `lib/client.js` from the hand-authored UI sources.
 *
 *   node scripts/build-client.mjs [--check]
 *
 * Inputs (in this order, all inlined inside the module factory):
 *   ui/markdown.js   pure markdown helpers (top-level `export ` stripped)
 *   ui/highlight.js  pure annotation helpers (top-level `export ` stripped)
 *   ui/app.js        React application; must define `clientMain(require)`
 * plus placeholders inside ui/app.js:
 *   __MINERU_CSS_JSON__         ← ui/styles.css      (JSON string)
 *   __MINERU_PANEL_ICON_JSON__  ← ui/panel-icon.svg  (JSON string)
 *   __MINERU_EMPTY_ART_JSON__   ← ui/empty-art.svg   (JSON string)
 *
 * Output is written to lib/client.js in the `window.__ModuleLoader__.load`
 * format the Harness web module system expects. Exits non-zero on any problem.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')
const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const bundleId = typeof packageJson.name === 'string' && packageJson.name !== '' ? packageJson.name : 'dsh-litnotes'

/** Read a required file, failing with a clear message. */
function read(rel) {
  const file = join(root, rel)
  if (!existsSync(file)) throw new Error(`missing required file: ${rel}`)
  return readFileSync(file, 'utf8')
}

/** Strip top-level ESM syntax; the bundle factory is a plain function scope. */
function toFactoryBody(rel, source) {
  const lines = source.split('\n')
  const out = []
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i]
    if (/^import\s/.test(line)) throw new Error(`${rel}:${i + 1}: import is not allowed in UI sources`)
    if (/^export\s+default\s/.test(line)) throw new Error(`${rel}:${i + 1}: default export is not allowed`)
    out.push(line.replace(/^export\s+/, ''))
  }
  return out.join('\n')
}

/** Replace one placeholder exactly once and verify it disappeared. */
function injectPlaceholder(source, placeholder, value, rel) {
  const count = source.split(placeholder).length - 1
  if (count !== 1) throw new Error(`${rel}: expected exactly one ${placeholder}, found ${count}`)
  return source.split(placeholder).join(value)
}

try {
  const markdown = toFactoryBody('ui/markdown.js', read('ui/markdown.js'))
  const highlight = toFactoryBody('ui/highlight.js', read('ui/highlight.js'))
  const chat = toFactoryBody('ui/chat.js', read('ui/chat.js'))
  const graph = toFactoryBody('ui/graph.js', read('ui/graph.js'))
  let app = toFactoryBody('ui/app.js', read('ui/app.js'))

  const css = read('ui/styles.css')
  const panelIcon = read('ui/panel-icon.svg').trim()
  const emptyArt = read('ui/empty-art.svg').trim()

  app = injectPlaceholder(app, '__MINERU_CSS_JSON__', JSON.stringify(css), 'ui/app.js')
  app = injectPlaceholder(app, '__MINERU_PANEL_ICON_JSON__', JSON.stringify(panelIcon), 'ui/app.js')
  app = injectPlaceholder(app, '__MINERU_EMPTY_ART_JSON__', JSON.stringify(emptyArt), 'ui/app.js')

  const body = [markdown, highlight, chat, graph, app].join('\n\n')
  if (/^export\s/m.test(body)) throw new Error('an `export ` statement survived body assembly')
  if (body.includes('__MINERU_')) throw new Error('an unreplaced __MINERU_ placeholder survived body assembly')
  if (!/function\s+clientMain\s*\(/.test(body)) throw new Error('ui/app.js must define clientMain(require)')

  const bundle = `/* ${bundleId} client bundle — generated by scripts/build-client.mjs; edit ui/** instead. */
window.__ModuleLoader__.load({
  id: '${bundleId}',
  factory(require) {
    'use strict';
    const React = require('react');
    const h = React.createElement;

${body}

    return clientMain(require);
  },
});
`

  const outDir = join(root, 'lib')
  mkdirSync(outDir, { recursive: true })
  const outFile = join(outDir, 'client.js')
  writeFileSync(outFile, bundle)

  // Parse the generated bundle with Node's own parser (module syntax is valid here).
  const syntax = spawnSync(process.execPath, ['--check', outFile], { encoding: 'utf8' })
  if (syntax.status !== 0) {
    throw new Error(`generated bundle failed node --check:\n${syntax.stderr}`)
  }

  const bytes = Buffer.byteLength(bundle)
  console.log(`[build-client] ${checkOnly ? 'checked' : 'wrote'} lib/client.js (${(bytes / 1024).toFixed(1)} KiB, ` +
    `${css.length} B css, ${panelIcon.length} B panel icon, ${emptyArt.length} B empty art)`)
} catch (error) {
  console.error(`[build-client] FAILED: ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
}
